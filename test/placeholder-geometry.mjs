import assert from 'node:assert/strict';
import JSZip from 'jszip';
import {XMLParser} from 'fast-xml-parser';
import {toPptx} from '../dist/index.js';
import {resolvePresentation} from '@openpresentation/opf-render';
const array = value => value === undefined ? [] : Array.isArray(value) ? value : [value];
const native = shape => array(shape['p:txBody']?.['a:p']).map(p => array(p['a:r']).map(r => r['a:t'] ?? '').join('')).join('\n');
const deck = {slides: [{layout: 'title-subtitle', title: 'Short title', subtitle: 'A short subtitle'}]};
const bound = resolvePresentation(deck).slides[0];
const title = bound.geometry.items.find(item => item.field === 'title');
const subtitle = bound.geometry.items.find(item => item.field === 'subtitle');
assert.equal(title.box.x, subtitle.box.x);
assert.equal(title.box.width, subtitle.box.width);
const bytes = await toPptx(deck);
const zip = await JSZip.loadAsync(bytes);
const xml = await zip.file('ppt/slides/slide1.xml').async('string');
assert.ok(xml.includes('Short title'));
assert.ok(xml.includes('A short subtitle'));
const shapes = array(new XMLParser({ignoreAttributes: false, attributeNamePrefix: ''}).parse(xml)['p:sld']['p:cSld']['p:spTree']['p:sp']);
const titleShape = shapes.find(shape => native(shape) === 'Short title');
const subtitleShape = shapes.find(shape => native(shape) === 'A short subtitle');
assert.ok(titleShape);
assert.ok(subtitleShape);
assert.equal(Number(titleShape['p:spPr']['a:xfrm']['a:off'].x), Number(subtitleShape['p:spPr']['a:xfrm']['a:off'].x));
console.log('Placeholder geometry: PPTX export consumes composeSlide heading origins with equal left edges.');
